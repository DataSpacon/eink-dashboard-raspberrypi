def add_advice():
    connection = sqlite3.connect(DATABASE)
    cursor = connection.cursor()

    for month, day, text in ADVICE:
        cursor.execute(
            """
            INSERT OR REPLACE INTO advice (month, day, text)
            VALUES (?, ?, ?)
            """,
            (month, day, text)
        )

    connection.commit()
    connection.close()

    print("Advice imported successfully.")
    print("Records imported:", len(ADVICE))


