def import_imieniny():
    connection = sqlite3.connect(DATABASE)
    cursor = connection.cursor()

    for month, day, names in IMIENINY:
        cursor.execute(
            """
            INSERT OR REPLACE INTO days (month, day, imieniny)
            VALUES (?, ?, ?)
            """,
            (month, day, names)
        )

    connection.commit()
    connection.close()

    print("Imieniny imported successfully.")
    print("Records imported:", len(IMIENINY))


